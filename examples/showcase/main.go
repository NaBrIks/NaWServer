//go:embed web/*
var assets embed.FS

type demo struct {
	started  time.Time
	requests atomic.Uint64
	echoes   atomic.Uint64
	clients  atomic.Int32
	mu       sync.Mutex
	profile  string
}

func main() {
	listen := flag.String("listen", "127.0.0.1:8788", "loopback HTTP address")
	pack := flag.String("pack", "", "generate gzip C++ assets header and exit")
	flag.Parse()
	if *pack != "" {
		if err := packAssets(*pack); err != nil {
			log.Fatal(err)
		}
		return
	}
	host, _, err := net.SplitHostPort(*listen)
	if err != nil || net.ParseIP(host) == nil || !net.ParseIP(host).IsLoopback() {
		log.Fatal("local demo must bind a numeric loopback address")
	}
	d := &demo{started: time.Now(), profile: "balanced"}
	log.Printf("SYNTHETIC DATA · local Go simulator, not ESP-IDF · http://%s", *listen)
	server := &http.Server{Addr: *listen, Handler: d.handler(), ReadHeaderTimeout: 5 * time.Second, ReadTimeout: 10 * time.Second, WriteTimeout: 10 * time.Second, IdleTimeout: 30 * time.Second, MaxHeaderBytes: 8192}
	log.Fatal(server.ListenAndServe())
}

func packAssets(destination string) error {
	var output bytes.Buffer
	output.WriteString("// Generated by go run . -pack main/assets.hpp. Do not edit.\n#pragma once\n#include <cstddef>\n#include <cstdint>\nnamespace showcase_assets {\n")
	for _, name := range []string{"index.html", "app.css", "app.js"} {
		data, err := assets.ReadFile("web/" + name)
		if err != nil {
			return err
		}
		var compressed bytes.Buffer
		writer, _ := gzip.NewWriterLevel(&compressed, gzip.BestCompression)
		if _, err = writer.Write(data); err != nil {
			return err
		}
		if err = writer.Close(); err != nil {
			return err
		}
		id := strings.NewReplacer(".", "_", "-", "_").Replace(name)
		fmt.Fprintf(&output, "inline const uint8_t %s[] = {\n", id)
		for i, b := range compressed.Bytes() {
			fmt.Fprintf(&output, "0x%02x,", b)
			if i%20 == 19 {
				output.WriteByte('\n')
			}
		}
		output.WriteString("\n};\n")
		log.Printf("%s: %d → %d bytes gzip", name, len(data), compressed.Len())
	}
	output.WriteString("}\n")
	if err := os.MkdirAll(filepath.Dir(destination), 0755); err != nil {
		return err
	}
	return os.WriteFile(destination, output.Bytes(), 0644)
}

func jsonReply(w http.ResponseWriter, status int, value any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(value)
}

func (d *demo) handler() http.Handler {
	web, _ := fs.Sub(assets, "web")
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("X-Showcase", "nawserver")
		w.Header().Set("X-Content-Type-Options", "nosniff")
		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Content-Security-Policy", "default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'")
		d.requests.Add(1)
		if r.URL.Path == "/ws" {
			d.websocket(w, r)
			return
		}
		if r.Method != "GET" && r.Method != "POST" {
			w.Header().Set("Allow", "GET, POST")
			http.Error(w, "method not allowed", 405)
			return
		}
		r.Body = http.MaxBytesReader(w, r.Body, 4096)
		if r.Method == "POST" {
			if err := r.ParseForm(); err != nil {
				http.Error(w, "body rejected", 400)
				return
			}
		}
		switch r.URL.Path {
		case "/api/telemetry":
			if !getOnly(w, r) {
				return
			}
			s := time.Since(d.started).Seconds()
			jsonReply(w, 200, map[string]any{"mode": "local", "device": "Go simulator / C3 model", "uptime_s": int(s), "free_heap": 249000 + int(2800*math.Sin(s/9)), "min_heap": 244000, "rssi_dbm": -53 + int(4*math.Sin(s/7)), "temperature_c": 29 + 2.6*math.Sin(s/11) + .7*math.Sin(s/3), "ws_clients": d.clients.Load(), "http_requests": d.requests.Load(), "ws_echoes": d.echoes.Load(), "sensor_synthetic": true})
		case "/api/echo":
			w.Header().Set("Content-Type", "text/plain; charset=utf-8")
			_, _ = io.WriteString(w, r.FormValue("value"))
		case "/api/control":
			u, p, ok := r.BasicAuth()
			if !ok || u != "demo" || p != "showcase-only" {
				w.Header().Set("WWW-Authenticate", `Basic realm="showcase"`)
				http.Error(w, "unauthorized", 401)
				return
			}
			if r.Method != "POST" {
				w.Header().Set("Allow", "POST")
				http.Error(w, "POST required", 405)
				return
			}
			if !sameOrigin(r) {
				http.Error(w, "origin rejected", 403)
				return
			}
			profile := r.PostFormValue("profile")
			if profile != "balanced" && profile != "quiet" && profile != "performance" {
				jsonReply(w, 400, map[string]string{"error": "invalid profile"})
				return
			}
			d.mu.Lock()
			d.profile = profile
			d.mu.Unlock()
			jsonReply(w, 200, map[string]string{"profile": profile, "storage": "RAM only", "effect": "demo only"})
		case "/api/stream":
			if !getOnly(w, r) {
				return
			}
			w.Header().Set("Content-Type", "text/plain; charset=utf-8")
			_, _ = io.WriteString(w, "nawserver stream: headers → content → response. Not SSE.")
		case "/health":
			if !getOnly(w, r) {
				return
			}
			jsonReply(w, 200, map[string]any{"ok": true, "mode": "local"})
		case "/go":
			if !getOnly(w, r) {
				return
			}
			http.Redirect(w, r, "/#capabilities", 302)
		case "/", "/app.css", "/app.js":
			if !getOnly(w, r) {
				return
			}
			name := strings.TrimPrefix(r.URL.Path, "/")
			if name == "" {
				name = "index.html"
			}
			data, _ := fs.ReadFile(web, name)
			mime := map[string]string{"index.html": "text/html; charset=utf-8", "app.css": "text/css; charset=utf-8", "app.js": "application/javascript; charset=utf-8"}
			w.Header().Set("Content-Type", mime[name])
			_, _ = w.Write(data)
		default:
			jsonReply(w, 404, map[string]string{"error": "route not found"})
		}
	})
}

func getOnly(w http.ResponseWriter, r *http.Request) bool {
	if r.Method == "GET" {
		return true
	}
	w.Header().Set("Allow", "GET")
	http.Error(w, "GET required", 405)
	return false
}
func sameOrigin(r *http.Request) bool {
	origin := r.Header.Get("Origin")
	if origin == "" {
		return true
	}
	u, err := url.Parse(origin)
	return err == nil && (u.Scheme == "http" || u.Scheme == "https") && u.Host == r.Host
}

// Minimal emulator, not a NaWServer transport implementation. Browsers send final,
// masked frames here. Fragmented frames are explicitly rejected (1003).
func (d *demo) websocket(w http.ResponseWriter, r *http.Request) {
	key, err := base64.StdEncoding.DecodeString(r.Header.Get("Sec-WebSocket-Key"))
	if r.Method != "GET" || !strings.EqualFold(r.Header.Get("Upgrade"), "websocket") || !headerToken(r.Header.Get("Connection"), "upgrade") || r.Header.Get("Sec-WebSocket-Version") != "13" || err != nil || len(key) != 16 || !sameOrigin(r) {
		http.Error(w, "invalid websocket handshake", 400)
		return
	}
	conn, rw, err := w.(http.Hijacker).Hijack()
	if err != nil {
		return
	}
	defer conn.Close()
	hash := sha1.Sum([]byte(r.Header.Get("Sec-WebSocket-Key") + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11"))
	_, _ = fmt.Fprintf(rw, "HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: %s\r\n\r\n", base64.StdEncoding.EncodeToString(hash[:]))
	if rw.Flush() != nil {
		return
	}
	d.clients.Add(1)
	defer d.clients.Add(-1)
	var writeMu sync.Mutex
	write := func(op byte, data []byte) error {
		writeMu.Lock()
		defer writeMu.Unlock()
		_ = conn.SetWriteDeadline(time.Now().Add(3 * time.Second))
		return writeFrame(conn, op, data)
	}
	done := make(chan struct{})
	defer close(done)
	go func() {
		ticker := time.NewTicker(5 * time.Second)
		defer ticker.Stop()
		for {
			select {
			case <-done:
				return
			case <-ticker.C:
				if write(1, []byte(`{"event":"tick","source":"synthetic-local"}`)) != nil {
					_ = conn.Close()
					return
				}
			}
		}
	}()
	for {
		_ = conn.SetReadDeadline(time.Now().Add(120 * time.Second))
		op, data, code, err := readFrame(rw.Reader)
		if err != nil {
			if code != 0 {
				_ = write(8, []byte{byte(code >> 8), byte(code)})
			}
			return
		}
		switch op {
		case 1, 2:
			d.echoes.Add(1)
			if write(op, data) != nil {
				return
			}
		case 8:
			_ = write(8, data)
			return
		case 9:
			if write(10, data) != nil {
				return
			}
		case 10:
		}
	}
}
func headerToken(value, expected string) bool {
	for _, t := range strings.Split(value, ",") {
		if strings.EqualFold(strings.TrimSpace(t), expected) {
			return true
		}
	}
	return false
}
func writeFrame(w io.Writer, op byte, data []byte) error {
	header := []byte{0x80 | op}
	n := len(data)
	if n < 126 {
		header = append(header, byte(n))
	} else {
		header = append(header, 126, byte(n>>8), byte(n))
	}
	_, err := w.Write(append(header, data...))
	return err
}
func readFrame(r *bufio.Reader) (byte, []byte, uint16, error) {
	fail := func(code uint16) (byte, []byte, uint16, error) { return 0, nil, code, errors.New("invalid frame") }
	a, err := r.ReadByte()
	if err != nil {
		return 0, nil, 0, err
	}
	b, err := r.ReadByte()
	if err != nil {
		return 0, nil, 0, err
	}
	op := a & 15
	if a&0x70 != 0 || b&0x80 == 0 || (op != 1 && op != 2 && op != 8 && op != 9 && op != 10) {
		return fail(1002)
	}
	if a&0x80 == 0 {
		return fail(1003)
	}
	n := uint64(b & 127)
	if n == 126 {
		var v uint16
		if err = binary.Read(r, binary.BigEndian, &v); err != nil {
			return 0, nil, 0, err
		}
		n = uint64(v)
		if n < 126 {
			return fail(1002)
		}
	} else if n == 127 {
		if err = binary.Read(r, binary.BigEndian, &n); err != nil {
			return 0, nil, 0, err
		}
		if n < 65536 || n>>63 != 0 {
			return fail(1002)
		}
	}
	if n > 4096 {
		return fail(1009)
	}
	if op >= 8 && (n > 125 || (op == 8 && n == 1)) {
		return fail(1002)
	}
	var mask [4]byte
	if _, err = io.ReadFull(r, mask[:]); err != nil {
		return 0, nil, 0, err
	}
	data := make([]byte, int(n))
	if _, err = io.ReadFull(r, data); err != nil {
		return 0, nil, 0, err
	}
	for i := range data {
		data[i] ^= mask[i%4]
	}
	if op == 1 && !utf8.Valid(data) {
		return fail(1007)
	}
	if op == 8 && len(data) >= 2 {
		code := binary.BigEndian.Uint16(data)
		if code < 1000 || code >= 5000 || code == 1004 || code == 1005 || code == 1006 || code == 1015 || (code >= 1016 && code < 3000) {
			return fail(1002)
		}
		if !utf8.Valid(data[2:]) {
			return fail(1007)
		}
	}
	return op, data, 0, nil
}
